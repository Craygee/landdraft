select table_name,role_name,privilege,
 case when to_regclass('public.'||table_name) is null then
  case when optional then 'OPTIONAL NOT INSTALLED' else 'MISSING TABLE' end
 when has_table_privilege(role_name,'public.'||table_name,privilege) then 'OK'
 else 'MISSING GRANT' end as status
from expected order by table_name,role_name,privilege;

-- Catalog and RLS inventory: review unknown tables rather than granting blindly.
select c.relname as table_name,c.relrowsecurity as rls_enabled,
 has_table_privilege('anon',c.oid,'SELECT') as anon_select,
 has_table_privilege('authenticated',c.oid,'SELECT') as signed_in_select,
 has_table_privilege('service_role',c.oid,'SELECT') as server_select,
 (select count(*) from pg_policy p where p.polrelid=c.oid) as policy_count,
 case when c.relname in ('profiles','projects','project_members','project_versions','project_shares','share_members','share_submissions','weather_provider_connections','project_email_aliases','project_inbound_emails','project_inbound_attachments','weather_product_entitlements','weather_provider_audit_events','ai_daily_usage','weather_license_reviews','weather_provider_catalog','weather_product_catalog','weather_chaser_presence','parcel_cache_policy','project_parcel_cache') then 'LANDDRAFT INVENTORY' else 'REVIEW UNCLASSIFIED' end as inventory
from pg_class c join pg_namespace n on n.oid=c.relnamespace
where n.nspname='public' and c.relkind in ('r','p') order by c.relname;

-- Sequence permissions are needed if future tables use serial/identity columns.
select n.nspname as schema_name,c.relname as sequence_name,
 has_sequence_privilege('authenticated',c.oid,'USAGE') as signed_in_usage,
 has_sequence_privilege('service_role',c.oid,'USAGE') as server_usage
from pg_class c join pg_namespace n on n.oid=c.relnamespace
where n.nspname='public' and c.relkind='S';

-- Defaults are reported, not modified globally.
select pg_get_userbyid(d.defaclrole) as creating_role,n.nspname as schema_name,
 d.defaclobjtype,d.defaclacl::text as default_permissions
from pg_default_acl d left join pg_namespace n on n.oid=d.defaclnamespace;

-- All exposed application functions, including their role access and search path.
select p.proname,pg_get_function_identity_arguments(p.oid) as arguments,
 p.prosecdef as security_definer,p.proconfig,
 has_function_privilege('anon',p.oid,'EXECUTE') as anon_execute,
 has_function_privilege('authenticated',p.oid,'EXECUTE') as signed_in_execute,
 has_function_privilege('service_role',p.oid,'EXECUTE') as server_execute
from pg_proc p join pg_namespace n on n.oid=p.pronamespace
where n.nspname='public' and not exists(select 1 from pg_depend d where d.objid=p.oid and d.classid='pg_proc'::regclass and d.deptype='e')
order by p.proname;
