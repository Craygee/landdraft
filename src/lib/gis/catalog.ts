export type CatalogCategory =
  | "Property"
  | "Oil & Gas"
  | "Water"
  | "Energy"
  | "Communications"
  | "Transportation"
  | "Boundaries"
  | "Environment"
  | "Demographics"
  | "Land";
export type ConnectionType = "live" | "refresh" | "download";

export interface CatalogEntry {
  id: string;
  name: string;
  agency: string;
  category: CatalogCategory;
  description: string;
  url?: string;
  downloadUrl?: string;
  sourcePage?: string;
  geometry: "polygon" | "line" | "point";
  keywords: string[];
  requiresViewport?: boolean;
  minZoom?: number;
  countyField?: string;
  where?: string;
  /** Fields to request where a publisher's service cannot answer outFields=*. */
  outFields?: string[];
  connection: ConnectionType;
  updateCadence: string;
  states: string[] | "US";
  license: string;
  /** Cartographic defaults applied only when the catalog layer is first added. */
  defaultStyle?: Partial<LayerStyle>;
  /** Cached image tiles that draw as an overlay rather than queryable features. */
  rendering?: "features" | "raster-tiles";
  tileSize?: 256 | 512;
  maxZoom?: number;
  /** Future state-data entitlement hook. It is metadata only; core mapping stays available. */
  entitlementKey?: string;
}

